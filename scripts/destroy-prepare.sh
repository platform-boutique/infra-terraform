#!/usr/bin/env bash
# Runs before the platform is destroyed (by the Destroy apply workflow, with the apply role). Terraform cannot see what runs INSIDE the
# cluster: Argo CD's applications, PersistentVolumeClaims and Services of type LoadBalancer create EBS volumes and load balancers that
# would be left behind and block the VPC. Remove them first. Needs WORKING_DIRECTORY and AWS_REGION (the workflow sets both).
#
# What lives in the cluster, and who removes it:
#   - everything Git deployed (Kyverno, External Secrets, the shop, Argo CD itself ...): this script, through Argo CD,
#   - Cilium, the SPIRE server and its volume (Terraform's, but the volume is an EBS volume Terraform does not know): this script
#     deletes the claim, the EBS CSI driver deletes the volume,
#   - Argo CD's and the root Application's Helm releases, the namespaces, the StorageClass: Terraform, after this script,
#   - the RDS instance (and everything else AWS): Terraform, as ordinary resources. Nothing here touches them.
#
# Never hangs: every kubectl call has a timeout, and what is still stuck afterwards (Argo CD finalizers, custom resources whose
# controller is already gone) has its finalizers removed. Whatever cannot be removed is reported by destroy-verify.sh.
set -uo pipefail

cluster="$(terraform -chdir="$WORKING_DIRECTORY" output -raw cluster_name 2>/dev/null || true)"
if [ -z "$cluster" ] || ! aws eks describe-cluster --name "$cluster" > /dev/null 2>&1; then
  echo "No cluster to empty."
  exit 0
fi

aws eks update-kubeconfig --name "$cluster" --region "$AWS_REGION"

# Every call gives up after 30 seconds if the API server does not answer (a long wait is spelled out with --timeout).
kc() { kubectl --request-timeout=30s "$@"; }
step() { echo "::group::$*"; }
endstep() { echo "::endgroup::"; }

# Removes the finalizers of an object (kind, name, optional namespace): the last resort for what would otherwise block forever.
strip_finalizers() {
  local kind="$1" name="$2" ns="${3:-}"
  if [ -n "$ns" ]; then
    kc -n "$ns" patch "$kind" "$name" --type merge -p '{"metadata":{"finalizers":null}}' > /dev/null 2>&1 || true
  else
    kc patch "$kind" "$name" --type merge -p '{"metadata":{"finalizers":null}}' > /dev/null 2>&1 || true
  fi
}

# Best effort from here: whatever cannot be removed is reported by destroy-verify.sh.

# --- 1. Argo CD ---------------------------------------------------------------------------------------------------------------------
# The Applications carry the resources-finalizer: deleting one makes Argo CD prune everything it deployed (PVCs, Services ...) first.
# Order matters:
#  a. The root Application and the `argocd` Application (Argo CD managing its own installation) lose their finalizers BEFORE they are
#     deleted. Otherwise deleting them would prune Argo CD itself, including the controller that has to process the other
#     finalizers, and the rest would hang. The root Application is deleted first so that nothing re-creates ApplicationSets or
#     Applications (it has selfHeal on).
#  b. ApplicationSets next (they would re-create Applications), which deletes the Applications they generated.
#  c. Then all remaining Applications, waiting for their finalizers (the pruning), with a time limit.
#  d. Anything still there gets its finalizer stripped, and is deleted.
if kc get ns argocd > /dev/null 2>&1 && kc get crd applications.argoproj.io > /dev/null 2>&1; then
  step "Argo CD: root Application, ApplicationSets, Applications"
  for app in platform-root argocd; do
    strip_finalizers applications.argoproj.io "$app" argocd
  done
  kc -n argocd delete applications.argoproj.io platform-root --ignore-not-found --wait=false || true
  kc -n argocd delete applicationsets.argoproj.io --all --wait=true --timeout=2m || true
  # Applications generated by the ApplicationSets are being garbage-collected now; delete whatever is left (with `argocd`, whose
  # finalizer is already gone, so Argo CD itself stays up until Terraform removes its release).
  kc -n argocd delete applications.argoproj.io --all --wait=true --timeout=10m || true

  # d. Stuck Applications: Argo CD cannot process its finalizers (the controller is down, or a resource refuses to go).
  for app in $(kc -n argocd get applications.argoproj.io -o name 2> /dev/null); do
    echo "Application ${app#*/} did not finish deleting: removing its finalizer."
    kc -n argocd patch "$app" --type merge -p '{"metadata":{"finalizers":null}}' > /dev/null 2>&1 || true
  done
  endstep
fi

# --- 2. Webhooks and custom resources of components that are gone ------------------------------------------------------------------
# Kyverno's webhooks stop the API server from admitting anything while their pods are gone (failurePolicy Fail): remove them.
# External Secrets' custom resources (ExternalSecrets, SecretStores ...) have a finalizer that only the operator removes.
step "Webhooks and custom resources left by removed components"
for kind in validatingwebhookconfigurations mutatingwebhookconfigurations; do
  kc delete "$kind" -l webhook.kyverno.io/managed-by=kyverno --ignore-not-found || true
  kc delete "$kind" -l app.kubernetes.io/instance=kyverno --ignore-not-found || true
done
for crd in $(kc get crd -o name 2> /dev/null | sed 's#.*/##' | grep -E '\.external-secrets\.io$' || true); do
  # "-" stands for "no namespace" (read would otherwise swallow an empty first field).
  kc get "$crd" -A -o json 2> /dev/null \
    | jq -r '.items[]? | select(.metadata.deletionTimestamp != null) | "\(.metadata.namespace // "-") \(.metadata.name)"' \
    | while read -r ns name; do
      if [ "$ns" = "-" ]; then strip_finalizers "$crd" "$name"; else strip_finalizers "$crd" "$name" "$ns"; fi
    done
done
endstep

# --- 3. SPIRE ---------------------------------------------------------------------------------------------------------------------
# The SPIRE server's data lives on a gp3 volume that the StatefulSet's claim holds. The StatefulSet belongs to the Cilium Helm release
# (Terraform), which removes it later, but a claim that a running pod uses cannot be deleted: stop the server first.
if kc -n cilium-spire get sts spire-server > /dev/null 2>&1; then
  step "SPIRE server: stop it so its volume can be released"
  kc -n cilium-spire scale sts/spire-server --replicas=0 || true
  kc -n cilium-spire wait --for=delete pod -l app=spire-server --timeout=2m || true
  endstep
fi

# --- 4. Volumes -------------------------------------------------------------------------------------------------------------------
# Every PersistentVolumeClaim (Postgres, Loki, Mimir, Grafana, SPIRE ...) is an EBS volume that Terraform does not know. The StorageClass
# reclaim policy is Delete, so deleting the claim makes the EBS CSI driver (still running: it is an add-on destroyed later) delete the
# volume. Wait for the volumes (PersistentVolumes) to disappear, which means the driver has deleted them in AWS.
step "PersistentVolumeClaims and the EBS volumes behind them"
kc delete pvc --all --all-namespaces --wait=true --timeout=5m || true
kc wait --for=delete pv --all --timeout=5m 2> /dev/null || true
left="$(kc get pv --no-headers 2> /dev/null | wc -l)"
if [ "$left" -gt 0 ]; then
  echo "::warning::$left PersistentVolume(s) still exist; their EBS volumes may be left in the account (scripts/destroy-verify.sh lists them, scripts/delete-leftover-volumes.sh deletes them)."
  kc get pv || true
fi
endstep

# --- 5. Load balancers ------------------------------------------------------------------------------------------------------------
# A Service of type LoadBalancer would make EKS create a Classic Load Balancer that Terraform does not know and that blocks the VPC.
# None should exist (Kyverno denies them), but a destroy must not depend on that.
step "Services of type LoadBalancer"
kc get svc --all-namespaces --field-selector spec.type=LoadBalancer -o json \
  | jq -r '.items[] | "\(.metadata.namespace) \(.metadata.name)"' \
  | while read -r ns name; do kc -n "$ns" delete svc "$name" --timeout=2m || true; done
endstep
exit 0
